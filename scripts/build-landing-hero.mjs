// Builds the landing hero: a static picture of the dark UAE map plus the exact outline path that
// the animated glow follows. Replaces running a live MapLibre map in the visitor's browser.
//
// Both come from ONE render of OpenFreeMap tiles (scripts/hero/render.html, in headless Chrome):
// the picture, and a black/white mask of the same camera from which the UAE land areas are traced.
// So the glow follows the borders and coast that are visible in the picture.
//
// Usage:  pnpm build-landing-hero          (needs Google Chrome and network access)
//         CHROME_PATH=/path/to/chrome pnpm build-landing-hero
// Output: apps/web/src/modules/landing/assets/hero-uae-{1440,2880}.webp
//         apps/web/src/modules/landing/hero-outline.data.ts
// Re-run only when the camera, colours or the map style in render.html change, then commit the output.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';

const root = path.resolve(fileURLToPath(import.meta.url), '../..');
const web = path.join(root, 'apps/web');
const landing = path.join(web, 'src/modules/landing');
const assets = path.join(landing, 'assets');

const CHROME_CANDIDATES = [
  process.env.CHROME_PATH,
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
  '/usr/bin/chromium-browser',
].filter(Boolean);
const chrome = CHROME_CANDIDATES.find((p) => existsSync(p));
if (!chrome) throw new Error('Chrome not found. Set CHROME_PATH.');

const maplibreDist = path.join(web, 'node_modules/maplibre-gl/dist');
const files = {
  '/': ['scripts/hero/render.html', 'text/html'],
  '/maplibre-gl.js': [path.join(maplibreDist, 'maplibre-gl.js'), 'text/javascript'],
  '/maplibre-gl.css': [path.join(maplibreDist, 'maplibre-gl.css'), 'text/css'],
  '/countries.json': [path.join(web, 'public/data/countries.json'), 'application/json'],
};

const server = createServer((req, res) => {
  const entry = files[req.url?.split('?')[0] ?? ''];
  if (!entry) {
    res.writeHead(404).end();
    return;
  }
  const [file, type] = entry;
  res.writeHead(200, { 'content-type': type }).end(readFileSync(path.isAbsolute(file) ? file : path.join(root, file)));
});
await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
const { port } = server.address();

const browser = await puppeteer.launch({
  executablePath: chrome,
  headless: true,
  defaultViewport: { width: 1440, height: 1800, deviceScaleFactor: 1 },
  args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--hide-scrollbars'],
});

try {
  const page = await browser.newPage();
  page.on('console', (m) => console.log('  [page]', m.text()));
  page.on('pageerror', (e) => console.error('  [page error]', e.message));
  await page.goto(`http://127.0.0.1:${port}/`, { waitUntil: 'load' });
  let result;
  try {
    result = await page.evaluate(() => window.generate());
  } catch (error) {
    const mask = await page.evaluate(() => window.maskPng).catch(() => null);
    if (mask) writeFileSync('/tmp/hero-mask.png', Buffer.from(mask, 'base64'));
    throw error;
  }

  mkdirSync(assets, { recursive: true });
  const sizes = { 1: 1440, 2: 2880 };
  for (const [ratio, name] of Object.entries(sizes)) {
    const buf = Buffer.from(result.images[ratio], 'base64');
    writeFileSync(path.join(assets, `hero-uae-${name}.webp`), buf);
    console.log(`hero-uae-${name}.webp  ${(buf.length / 1024).toFixed(0)} KB`);
  }

  const { outline } = result;
  const [x0, y0, x1, y1] = outline.bbox;
  const source = `// Generated by scripts/build-landing-hero.mjs. Do not edit.
// The UAE outline traced from the same render as assets/hero-uae-*.webp, in that picture's pixels.

/** Size of the largest picture, the coordinate space of the paths below. */
export const HERO_SIZE = { width: ${outline.width}, height: ${outline.height} } as const;

/** Bounding box of the outline in picture pixels: [left, top, right, bottom]. */
export const HERO_OUTLINE_BOX = [${x0}, ${y0}, ${x1}, ${y1}] as const;

/** Mainland ring, clockwise from its westernmost point. */
export const HERO_MAIN_PATH =
  ${JSON.stringify(outline.main)};

/** Islands, enclaves and the Musandam exclave: one subpath each. */
export const HERO_REST_PATH =
  ${JSON.stringify(outline.rest)};
`;
  writeFileSync(path.join(landing, 'hero-outline.data.ts'), source);
  console.log('hero-outline.data.ts', outline.stats, 'bbox', outline.bbox);
} finally {
  await browser.close();
  server.close();
}
